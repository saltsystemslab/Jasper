#!/usr/bin/env python3
"""Export the estimated-vs-true distortion grid as pgfplots data + a .tex figure.

Bins the edge-score CSVs from distortion_test (one k, one sampling mode) into
2D histograms and writes, into --out:

    <prefix>_<dataset>_<method>.csv   x y logc  (bin centers; logc = log10(count),
                                      nan for empty bins, which pgfplots skips)
    <prefix>.tex                      a figure* with a 2 x 3 groupplot:
                                      rows = datasets, columns = methods

Each row shares one axis range (so the three estimators of a dataset are
directly comparable) and every panel shares one color scale. Axes are on the
||q-v|| scale (square root of the stored squared L2).

    python3 scripts/export_distortion_pgf.py <run>/trajectory --k 16 --out <run>

In the LaTeX project, the preamble needs
    \\usepackage{pgfplots}  \\usepgfplotslibrary{groupplots}
and the figure finds its CSVs through \\distortiondir (default: the directory
the .tex is compiled from); \\newcommand{\\distortiondir}{figs/distortion}
before \\input-ing the figure points it elsewhere.
"""
from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

import numpy as np
import pandas as pd

METHODS = [("lsh", "CPH"), ("pq", "PQ"), ("rabitq", "RaBitQ")]
DS_LABEL = {"deep10M": "Deep 10M", "sra50": "SRA50", "bigann10M": "BigANN 10M",
            "gist": "Gist", "openai": "OpenAI", "sra500": "SRA500"}
# Single-hue sequential ramp (light -> dark blue), same as plot_distortion.py.
RAMP = ["205,226,251", "158,197,244", "109,167,236", "57,135,229",
        "37,106,191", "24,79,149", "13,54,107"]


def load(path: Path) -> tuple[np.ndarray, np.ndarray]:
    d = pd.read_csv(path, usecols=["exact", "est"])
    return np.sqrt(d.exact.clip(lower=0).to_numpy()), np.sqrt(d.est.clip(lower=0).to_numpy())


def nice_ticks(lo: float, hi: float, n: int = 4) -> list[float]:
    raw = (hi - lo) / n
    mag = 10 ** math.floor(math.log10(raw))
    step = min((s * mag for s in (1, 2, 2.5, 5, 10) if s * mag >= raw), default=10 * mag)
    first = math.ceil(lo / step) * step
    return [round(first + i * step, 10) for i in range(n + 2) if first + i * step <= hi + 1e-12]


def fmt(v: float) -> str:
    return f"{v:.6g}"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("data_dir", type=Path, help="trajectory/ or random/ directory of edge-score CSVs")
    ap.add_argument("--k", type=int, default=16)
    ap.add_argument("--datasets", nargs="*", default=["deep10M", "sra50"])
    ap.add_argument("--bins", type=int, default=64)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--prefix", default=None, help="file prefix (default: distortion_<mode>_k<k>)")
    args = ap.parse_args()

    mode = args.data_dir.name.rstrip("/")
    prefix = args.prefix or f"distortion_{mode}_k{args.k}"
    args.out.mkdir(parents=True, exist_ok=True)

    rows = []           # per dataset: (lo, hi, ticks)
    max_count = 1
    for ds in args.datasets:
        data = {}
        for m, _ in METHODS:
            p = args.data_dir / f"{ds}_{m}_k{args.k}.csv"
            if not p.exists():
                print(f"missing {p}", file=sys.stderr)
                return 1
            data[m] = load(p)
        allv = np.concatenate([np.concatenate(v) for v in data.values()])
        lo, hi = np.percentile(allv, [0.05, 99.95])
        pad = 0.03 * (hi - lo)
        lo, hi = lo - pad, hi + pad
        edges = np.linspace(lo, hi, args.bins + 1)
        centers = (edges[:-1] + edges[1:]) / 2
        for m, _ in METHODS:
            t, e = data[m]
            h, _, _ = np.histogram2d(t, e, bins=[edges, edges])  # h[x_bin, y_bin]
            max_count = max(max_count, int(h.max()))
            path = args.out / f"{prefix}_{ds}_{m}.csv"
            with open(path, "w") as f:
                f.write("x y logc\n")
                for j, yc in enumerate(centers):        # x varies fastest (mesh/ordering=x varies)
                    for i, xc in enumerate(centers):
                        c = h[i, j]
                        f.write(f"{fmt(xc)} {fmt(yc)} {fmt(math.log10(c)) if c > 0 else 'nan'}\n")
        rows.append((ds, lo, hi, nice_ticks(lo, hi)))

    log_max = math.log10(max_count)
    cticks = list(range(0, int(math.floor(log_max)) + 1))
    n_rows = len(rows)

    # ── .tex ──
    L = []
    w = L.append
    w(f"% Estimated vs true ||q-v|| for every edge estimator at r={args.k} ({mode} sampling).")
    w(f"% Generated by scripts/export_distortion_pgf.py from {args.data_dir}")
    w("% Needs in the preamble: \\usepackage{pgfplots}  \\usepgfplotslibrary{groupplots}")
    w("% CSVs are read from \\distortiondir; define it before \\input to move them.")
    w("\\providecommand{\\distortiondir}{.}")
    w("\\pgfplotsset{colormap={distortionblue}{" +
      " ".join(f"rgb255=({c})" for c in RAMP) + "}}")
    w("\\begin{figure*}[t]")
    w("\\centering")
    w("\\begin{tikzpicture}")
    w("\\def\\dpanel{4.0cm}\\def\\dvsep{1.25cm}")
    w("\\begin{groupplot}[")
    w(f"  group style={{group size=3 by {n_rows}, horizontal sep=0.35cm, vertical sep=\\dvsep,")
    w("               yticklabels at=edge left},")
    w("  scale only axis, width=\\dpanel, height=\\dpanel,")
    w("  colormap name=distortionblue,")
    w(f"  point meta min=0, point meta max={fmt(log_max)},")
    w("  enlargelimits=false, axis on top,")
    w("  tick label style={font=\\scriptsize}, label style={font=\\footnotesize},")
    w("  title style={font=\\footnotesize, yshift=-3pt},")
    w("  tick align=outside, major tick length=2pt,")
    w("  xlabel={true $\\|q-v\\|$},")
    w("  unbounded coords=jump,")
    w("]")
    for r, (ds, lo, hi, ticks) in enumerate(rows):
        tick_str = ",".join(fmt(t) for t in ticks)
        for c, (m, label) in enumerate(METHODS):
            opts = [f"xmin={fmt(lo)}, xmax={fmt(hi)}, ymin={fmt(lo)}, ymax={fmt(hi)}",
                    f"xtick={{{tick_str}}}, ytick={{{tick_str}}}"]
            if r == 0:
                opts.append(f"title={{{label} $r={args.k}$}}")
            if c == 0:
                opts.append(f"ylabel={{{DS_LABEL.get(ds, ds)}: est.\\ $\\|q-v\\|$}}")
            if r == 0 and c == len(METHODS) - 1:
                ctick = ",".join(str(t) for t in cticks)
                clab = ",".join(f"$10^{{{t}}}$" for t in cticks)
                opts.append("colorbar, colorbar style={at={(1.08,1)}, anchor=north west,")
                opts.append(f"  width=0.18cm, height={n_rows}*\\dpanel+{n_rows - 1}*\\dvsep,")
                opts.append(f"  ytick={{{ctick}}}, yticklabels={{{clab}}},")
                opts.append("  ylabel={count}, ylabel style={font=\\footnotesize},")
                opts.append("  tick label style={font=\\scriptsize}, major tick length=2pt}")
            w("\\nextgroupplot[" + ",\n  ".join(opts) + "]")
            w(f"\\addplot[matrix plot*, mesh/cols={args.bins}, point meta=explicit]")
            w(f"  table[x=x, y=y, meta=logc] {{\\distortiondir/{prefix}_{ds}_{m}.csv}};")
            w(f"\\addplot[densely dashed, black!60, line width=0.5pt] coordinates "
              f"{{({fmt(lo)},{fmt(lo)}) ({fmt(hi)},{fmt(hi)})}};")
    w("\\end{groupplot}")
    w("\\end{tikzpicture}")
    w("\\caption{Estimation distortion of each edge estimator at $r=" + str(args.k) + "$. "
      "We ran the beam search on the query set, sampled 10{,}000 popped nodes $u$ "
      "uniformly from the search trajectories, and estimated the distance from the "
      "query to every neighbor $v$ of $u$. X-axis is the exact distance, y-axis the "
      "estimate; color is the number of edges per bin (log scale).}")
    w(f"\\label{{fig:distortion-{mode}-k{args.k}}}")
    w("\\end{figure*}")
    tex = args.out / f"{prefix}.tex"
    tex.write_text("\n".join(L) + "\n")
    print(f"wrote {tex}")
    for ds, lo, hi, _ in rows:
        print(f"  {ds}: range [{lo:.4g}, {hi:.4g}], {args.bins}x{args.bins} bins")
    print(f"  color scale: 1 .. {max_count} edges/bin (log)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
